    fn tmp() -> (tempfile::TempDir, PathBuf) {
        let d = tempfile::tempdir().unwrap();
        let p = d.path().join("argus/config.toml");
        (d, p)
    }

    #[test]
    fn ensure_exists_writes_once() {
        let (_d, p) = tmp();
        assert!(ensure_exists(&p).unwrap());
        std::fs::write(&p, "# mine\n").unwrap();
        assert!(!ensure_exists(&p).unwrap());
        assert_eq!(
            std::fs::read_to_string(&p).unwrap(),
            "# mine\n",
            "never overwritten"
        );
    }

    #[test]
    fn add_roots_creates_config_below_the_documented_key() {
        let (d, p) = tmp();
        let r = d.path().join("code");
        std::fs::create_dir(&r).unwrap();
        let r2 = add_roots(&p, std::slice::from_ref(&r)).unwrap();
        assert_eq!((r2.added.len(), r2.file.as_path()), (1, p.as_path()));
        let text = std::fs::read_to_string(&p).unwrap();
        let i = text
            .lines()
            .position(|l| l.starts_with("# roots = "))
            .unwrap();
        assert!(
            text.lines().nth(i + 1).unwrap().starts_with("roots = ["),
            "{text}"
        );
        let c = Config::parse(&text).unwrap();
        assert_eq!(c.roots, vec![std::fs::canonicalize(&r).unwrap()]);
    }

    #[test]
    fn add_roots_preserves_user_edits_and_skips_duplicates() {
        let (d, p) = tmp();
        let a = d.path().join("a");
        let b = d.path().join("b");
        std::fs::create_dir(&a).unwrap();
        std::fs::create_dir(&b).unwrap();
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        let a_canon = std::fs::canonicalize(&a).unwrap();
        std::fs::write(
            &p,
            format!(
                "# my notes\nroots = [\"{}\"] # trailing\nmax_depth = 3\n",
                a_canon.display()
            ),
        )
        .unwrap();
        let r = add_roots(&p, std::slice::from_ref(&a)).unwrap();
        assert!(
            r.added.is_empty() && r.already.len() == 1,
            "already present"
        );
        assert_eq!(
            add_roots(&p, &[b.clone(), b.clone()]).unwrap().added.len(),
            1,
            "deduplicated within one call"
        );
        let text = std::fs::read_to_string(&p).unwrap();
        assert!(
            text.starts_with("# my notes\n")
                && text.contains("# trailing")
                && text.contains("max_depth = 3"),
            "{text}"
        );
        assert_eq!(Config::parse(&text).unwrap().roots.len(), 2);
    }

    #[test]
    fn add_rejects_missing_dirs_and_bad_roots() {
        let (d, p) = tmp();
        assert!(matches!(
            add_roots(&p, &[d.path().join("nope")]),
            Err(EditError::NoSuchDir(_))
        ));
        std::fs::write(&p, "roots = \"~/dev\"\n").unwrap();
        assert!(matches!(
            add_roots(&p, &[d.path().to_path_buf()]),
            Err(EditError::RootsNotArray { .. })
        ));
    }

    #[test]
    fn remove_roots_including_vanished_dirs() {
        let (d, p) = tmp();
        let a = d.path().join("a");
        let b = d.path().join("b");
        std::fs::create_dir(&a).unwrap();
        std::fs::create_dir(&b).unwrap();
        add_roots(&p, &[a.clone(), b.clone()]).unwrap();
        std::fs::remove_dir(&b).unwrap();
        let r = remove_roots(&p, &[std::fs::canonicalize(d.path()).unwrap().join("b")]).unwrap();
        assert_eq!(r.removed.len(), 1, "a vanished directory still matches");
        let r = remove_roots(&p, std::slice::from_ref(&b)).unwrap();
        assert!(
            r.removed.is_empty() && r.not_roots.len() == 1,
            "already removed"
        );
        let c = Config::parse(&std::fs::read_to_string(&p).unwrap()).unwrap();
        assert_eq!(c.roots, vec![std::fs::canonicalize(&a).unwrap()]);
    }

    #[test]
    fn mark_lists_are_edited_in_place() {
        let d = tempfile::tempdir().unwrap();
        let p = d.path().join("config.toml");
        let text = "# my config\nroots = [\"~/dev\"]\nfavourite = [\"a/x\", \"b/*\"] # keep\n\n[ui]\ntheme = \"dark\"\n";
        std::fs::write(&p, text).unwrap();
        let before = Config::parse(text).unwrap();
        // nothing changed: the file isn't touched
        update_mark_lists(&p, &before, &before).unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), text);
        let mut after = before.clone();
        after.favourite = vec!["b/*".into(), "c/y".into()];
        after.ignore = vec!["!d/z".into()];
        update_mark_lists(&p, &before, &after).unwrap();
        let out = std::fs::read_to_string(&p).unwrap();
        let c = Config::parse(&out).unwrap();
        assert_eq!(c.favourite, ["b/*", "c/y"]);
        assert_eq!(c.ignore, ["!d/z"], "created when missing");
        assert!(c.sync.is_empty());
        // the rest of the file is as written
        assert!(
            out.starts_with("# my config\nroots = [\"~/dev\"]\n"),
            "{out}"
        );
        assert!(
            out.contains("# keep") && out.contains("theme = \"dark\""),
            "{out}"
        );
        assert_eq!(c.ui.theme, "dark");
    }

    #[test]
    fn mark_lists_create_the_config_if_needed() {
        let d = tempfile::tempdir().unwrap();
        let p = d.path().join("new/config.toml");
        let before = Config::default();
        let after = Config {
            sync: vec!["acme/*".into()],
            ..Config::default()
        };
        update_mark_lists(&p, &before, &after).unwrap();
        let c = Config::parse(&std::fs::read_to_string(&p).unwrap()).unwrap();
        assert_eq!(c.sync, ["acme/*"]);
        assert_eq!(c.max_depth, Config::default().max_depth);
    }
